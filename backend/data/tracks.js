export function curatedSuggestionsForMood(mood, limit = 3, preferredGenre = null) {
  let matches = TRACKS.filter((t) => t.moods.includes(mood));
  if (preferredGenre && preferredGenre !== "all") {
    const genreMatches = matches.filter((t) => t.tag === preferredGenre);
    if (genreMatches.length) matches = genreMatches;
  }
  const pool = matches.length ? matches : TRACKS.filter((t) => t.moods.includes("okay"));
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, limit);
}
